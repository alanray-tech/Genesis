"""Rows where Genesis is closer than CGQ to the 50-digit exact value, recorded to improve CGQ's accuracy later.

    python bench/ipc_formulas/cgq_accuracy.py [--run cuda_fast-math-false]

Reads the exact values of referee.npz (referee.py), both CGQ builds and the Genesis run from cases.DATA, and writes
cgq_accuracy.md to cases.RESULTS: per refereed row, the error of CGQ (production and IEEE builds) and of Genesis
against the exact value, relative to the largest entry of that row's exact output, then the input rows to replay them.
"""

import argparse

import numpy as np

from cases import CASES, DATA, RESULTS


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run", default="cuda_fast-math-false")
    args = parser.parse_args()
    data = DATA
    referee = np.load(data / "referee.npz")
    lines = [
        "# Where Genesis is closer to the exact value than CGQ",
        "",
        "Errors against the 50-digit exact value (referee.py), relative to the largest entry of the row's exact output.",
        "'CGQ fma' is CGQ as production builds it, 'CGQ ieee' the --fmad=false build. Generated by cgq_accuracy.py.",
        "",
        "| case | set | row | flag | CGQ fma | CGQ ieee | Genesis | CGQ fma / Genesis |",
        "|---|---|---|---|---|---|---|---|",
    ]
    replay = []
    with np.load(data / "inputs.npz") as inputs, np.load(data / "out_cgq_fmad-true.npz") as fma, np.load(
        data / "out_cgq_fmad-false.npz"
    ) as ieee, np.load(data / f"out_genesis_{args.run}.npz") as genesis:
        for name in referee.files:
            if not name.endswith("/rows"):
                continue
            key = name[: -len("/rows")]
            if key.split("/")[0] != "barrier_ee":
                continue
            rows, exact = referee[f"{key}/rows"], referee[f"{key}/exact"]
            real = ~np.isnan(exact[0])
            for i, i_r in enumerate(rows):
                e = exact[i, real]
                scale = np.abs(e).max()
                errors = [np.abs(out[key][i_r, real] - e).max() / scale for out in (fma, ieee, genesis)]
                if errors[2] >= errors[0]:
                    continue
                lines.append(
                    f"| {key.split('/')[0]} | {key.split('/', 1)[1]} | {i_r} | {int(fma[key][i_r, 0])} | "
                    f"{errors[0]:.1e} | {errors[1]:.1e} | {errors[2]:.1e} | {errors[0] / max(errors[2], 1e-300):.0e} |"
                )
                replay.append((key, i_r, inputs[key][i_r]))
    lines += [
        "",
        f"Input rows ({CASES['barrier_ee'].n_inputs} columns: 4 points, 4 rest points, d_hat, xi, kappa; cases.py):",
        "",
    ]
    for key, i_r, row in replay:
        lines.append(f"- {key} row {i_r}: [{', '.join(f'{v:.17g}' for v in row)}]")
    path = RESULTS / "cgq_accuracy.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(replay)} rows, wrote {path}")


if __name__ == "__main__":
    main()
